def _canonical_log_message(msg):
    """Upstream embeds ``str(list)`` built from a set intersection in the
    blocklist log line; sort the bracketed names so the comparison doesn't
    depend on set iteration order."""
    prefix = "Removed the following bad nodes: "
    if isinstance(msg, str) and msg.startswith(prefix):
        import ast

        try:
            names = ast.literal_eval(msg[len(prefix) :])
            return prefix + str(sorted(names))
        except (ValueError, SyntaxError):
            return msg
    return msg


def mask_log_timestamps(obj):
    """Replace 'timestamp' values inside log-entry dicts with a fixed token
    and canonicalize set-order-dependent log messages."""
    if isinstance(obj, dict):
        out = {}
        for k, v in obj.items():
            if k == "timestamp" and isinstance(v, str):
                out[k] = "<ts>"
            elif k == "message":
                out[k] = mask_log_timestamps(_canonical_log_message(v))
            else:
                out[k] = mask_log_timestamps(v)
        return out
    if isinstance(obj, list):
        return [mask_log_timestamps(v) for v in obj]
    return obj


def _multiset(items):
    return sorted(json.dumps(i, sort_keys=True, default=str) for i in items)


def assert_parity(actual, golden, path="$"):
    if isinstance(golden, dict):
        assert isinstance(actual, dict), f"{path}: {type(actual)} != dict"
        assert set(actual.keys()) == set(
            golden.keys()
        ), f"{path}: keys {sorted(actual.keys())} != {sorted(golden.keys())}"
        for k in golden:
            assert_parity(actual[k], golden[k], f"{path}.{k}")
    elif isinstance(golden, list):
        assert isinstance(actual, list), f"{path}: {type(actual)} != list"
        assert len(actual) == len(
            golden
        ), f"{path}: length {len(actual)} != {len(golden)}"
        try:
            for i, (a, g) in enumerate(zip(actual, golden)):
                assert_parity(a, g, f"{path}[{i}]")
        except AssertionError:
            # order-insensitive fallback for set-union ordering divergence
            assert _multiset(actual) == _multiset(
                golden
            ), f"{path}: list contents differ (even unordered)"
    elif isinstance(golden, float) or isinstance(actual, float):
        assert actual == pytest.approx(
            golden, rel=1e-9, abs=1e-12
        ), f"{path}: {actual} != {golden}"
    else:
        assert actual == golden, f"{path}: {actual!r} != {golden!r}"


def jsonable(obj):
    def coerce(o):
        try:
            return float(o)
        except (TypeError, ValueError):
            return str(o)

    return json.loads(json.dumps(obj, default=coerce))


