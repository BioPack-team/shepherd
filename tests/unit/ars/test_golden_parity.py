def _validate_cases():
    aragorn = load("response_aragorn.json")
    cases = {
        "aragorn": aragorn,
        "arax": load("response_arax.json"),
        "empty": load("response_empty.json"),
        "blocklist": load("response_blocklist.json"),
        "no_message": {"foo": "bar"},
    }
    broken_edge = copy.deepcopy(aragorn)
    del broken_edge["message"]["knowledge_graph"]["edges"]["e1"]["predicate"]
    cases["edge_missing_predicate"] = broken_edge

    broken_result = copy.deepcopy(aragorn)
    del broken_result["message"]["results"][0]["node_bindings"]
    cases["result_missing_node_bindings"] = broken_result

    broken_qg = copy.deepcopy(aragorn)
    broken_qg["message"]["query_graph"]["nodes"]["sn"]["categories"] = "notalist"
    cases["qg_categories_not_list"] = broken_qg

    broken_binding = copy.deepcopy(aragorn)
    del broken_binding["message"]["results"][0]["node_bindings"]["sn"][0]["id"]
    cases["binding_missing_id"] = broken_binding

    broken_kg = copy.deepcopy(aragorn)
    broken_kg["message"]["knowledge_graph"] = {"nodes": {}}
    cases["kg_missing_edges"] = broken_kg

    results_not_list = copy.deepcopy(aragorn)
    results_not_list["message"]["results"] = {"a": 1}
    cases["results_not_list"] = results_not_list
    return cases


@pytest.mark.parametrize("name", sorted(GOLDENS["validate"].keys()))
def test_validate_verdict_parity(name):
    cases = _validate_cases()
    assert (
        validate(cases[name]) == GOLDENS["validate"][name]
    ), f"verdict mismatch for {name}"


def test_normalized_scores_survive_shepherd_blob_codec():
    """Regression: rankdata yields numpy.float64; upstream's stdlib-json
    storage accepts it but Shepherd's orjson blob codec rejects numpy
    scalars, so pre-merged callbacks silently failed to save and merges
    KeyError'd. normalized_score must be a plain float."""
    from shepherd_utils.db import decode_message, encode_message

    results = [{"analyses": [{"score": 0.9}]}, {"analyses": [{"score": 0.1}]}]
    normalized = ars_premerge.normalizeScores(results)
    assert all(type(r["normalized_score"]) is float for r in normalized)
    # the whole premerged payload must round-trip through the blob codec
    payload = {"message": {"results": normalized}}
    assert decode_message(encode_message(payload)) == payload
