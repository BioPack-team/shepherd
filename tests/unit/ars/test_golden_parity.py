"""Layer-1 golden parity: Shepherd's ARS ports vs. the real upstream outputs.

tests/fixtures/ars_goldens/goldens.json is generated by RUNNING the pinned
NCATSTranslator/Relay code over tests/fixtures/ars_corpus/ (see
scripts/ars_parity/generate_goldens.py). These tests run the Shepherd ports
over the same corpus and require identical output.

Comparison rules:
  - dicts/scalars: exact
  - lists: exact order first; on mismatch, fall back to multiset equality
    (order-insensitive) -- the upstream code has a few list(set(...)) unions
    whose ordering is hash-seed dependent
  - log-entry "timestamp" values are masked (upstream stamps wall-clock)
"""

